import { expect,test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { selectWorkspaceReviewer } from "./research-review-helpers";
test.skip(!process.env.E2E_RESEARCH_COMPONENT_FIXTURE,"Requires isolated ordinary UI/Gateway peers, not hosted users.");
for(const theme of ["light","dark"])test(`${theme}: saved answer, interrupted finding retry, revision and independent review survive reload`,async({page},testInfo)=>{
  const actor=randomUUID(),reviewer=randomUUID(),question=`Synthetic finding ${testInfo.project.name} ${theme} ${randomUUID()}`;
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  await page.goto(`/?actor=${actor}&reviewer=${reviewer}&theme=${theme}`);
  await expect(page.getByRole("button",{name:"Save plan",exact:true})).toBeEnabled();
  await page.getByLabel("Mode",{exact:true}).selectOption("QUICK_LOOKUP");
  await page.getByLabel("Question",{exact:true}).fill(question);
  await page.getByLabel("Completion criteria").fill("Inspect the exact source with an independent reviewer.");
  await page.getByRole("checkbox",{name:"Synthetic policy.txt",exact:true}).check();
  await page.getByRole("button",{name:"Save plan",exact:true}).click();
  await page.getByRole("checkbox",{name:/I confirm that all questions/}).check();
  await page.getByRole("button",{name:"Start research",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"Execution finished"})).toBeVisible();
  const save=page.getByRole("button",{name:"Save as finding",exact:true});await save.click();
  await expect(page.getByRole("alert")).toContainText("not confirmed");await save.click();
  const open=page.getByRole("link",{name:"Open saved finding",exact:true});
  await expect(open).toBeVisible();const href=await open.getAttribute("href");
  await open.click();await expect(page.getByLabel("Title",{exact:true})).toHaveValue(question);
  await expect(page.getByText("The mass is 1.005 kg [S1].",{exact:true})).toBeVisible();
  await expect(page.getByText(/SHA256 [a-f0-9]{64}/)).toBeVisible();
  await expect(page.getByRole("button",{name:"Approve revision",exact:true})).toBeDisabled();
  await page.getByRole("textbox",{name:"Authored finding",exact:true}).fill("Synthetic authored context after checking the original.");
  await page.getByRole("button",{name:"Save finding",exact:true}).click();
  await expect(page.getByRole("heading",{name:/Revision 2/})).toBeVisible();
  await selectWorkspaceReviewer(page,reviewer);
  await page.getByRole("button",{name:"Share for review",exact:true}).click();
  await expect(page.getByText("1 explicitly shared members",{exact:true})).toBeVisible();
  await page.goto(`${href}&actor=${reviewer}&theme=${theme}`);
  await expect(page.getByLabel("Title",{exact:true})).toHaveValue(question);
  await page.getByLabel("Review comment",{exact:true}).fill("Independent synthetic review of the original source.");
  await page.getByRole("button",{name:"Approve revision",exact:true}).click();
  await expect(page.getByText("approved: Independent synthetic review of the original source.",{exact:true})).toBeVisible();
  await page.reload();await expect(page.getByText("approved: Independent synthetic review of the original source.",{exact:true})).toBeVisible();
  await expect(page.locator("time[datetime]")).toBeVisible();
  await expect(page.getByRole("textbox",{name:"Authored finding",exact:true})).toHaveValue("Synthetic authored context after checking the original.");
  await expect(page.getByRole("button",{name:"Export JSON-LD & receipt",exact:true})).toBeDisabled();
  await expect(page.getByRole("link",{name:"Inspect source document",exact:true})).toHaveAttribute("href","/documents/60606060-6060-4060-8060-606060606060");
  await expect(page.locator("html")).toHaveClass(theme==="dark"?/dark/:/^$/);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.getByRole("region",{name:"Findings workbench",exact:true}).screenshot({path:testInfo.outputPath(`research-finding-${theme}.png`)});
  await page.getByRole("region",{name:"Evidence and reviews",exact:true}).screenshot({path:testInfo.outputPath(`research-finding-evidence-${theme}.png`)});
});
