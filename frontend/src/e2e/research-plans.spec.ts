import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
test.skip(!process.env.E2E_RESEARCH_COMPONENT_FIXTURE,"Requires isolated synthetic UI/API/Gateway peers, not a hosted origin.");
for (const theme of ["light","dark"]) test(`${theme}: save, reload, inspect and copy a twelve-mode research draft`, async ({page}, testInfo) => {
  const errors: string[]=[];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/?theme=${theme}&actor=${randomUUID()}`);
  const save=page.getByRole("button",{name: "Save plan",exact: true});
  await expect(save).toBeEnabled();
  await expect(page.getByLabel("Mode").locator("option")).toHaveCount(12);
  const question=`Synthetic research ${theme} ${testInfo.project.name}`;
  await page.getByLabel("Mode").selectOption("COMPARE");
  await page.getByLabel("Question",{exact: true}).fill(question);
  await page.getByLabel("Jurisdiction").fill("Synthetic jurisdiction");
  await page.getByLabel("Subquestions",{exact: true}).fill("What changed?");
  await page.getByLabel("Completion criteria").fill("Inspect the exact evidence");
  await page.getByRole("checkbox",{name: "Synthetic policy.txt",exact: true}).check();
  await save.click();
  await expect(page.getByRole("status")).toHaveText("Saved draft. Execution has not started.");
  await expect(page.getByRole("heading",{name: "Compare",exact: true})).toBeFocused();
  await page.reload();
  await page.getByRole("button",{name: `Open research plan: ${question}`,exact: true}).click();
  await expect(page.getByRole("status")).toHaveText("Saved draft. Execution has not started.");
  await expect(page.getByText("60606060-6060-4060-8060-606060606060",{exact: true})).toBeVisible();
  await expect(page.getByText("Synthetic jurisdiction",{exact: true})).toBeVisible();
  await page.getByRole("button",{name: "Copy to a new plan"}).click();
  await expect(page.getByLabel("Question",{exact: true})).toHaveValue(question);
  await expect(page.getByLabel("Mode")).toHaveValue("COMPARE");
  await page.getByLabel("Question",{exact: true}).fill(`${question} copy`);
  await save.click();
  await expect(page.getByRole("button",{name: `Open research plan: ${question} copy`,exact: true})).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.screenshot({path: testInfo.outputPath("research-plan-stored.png"),fullPage: true});
});
test("an interrupted response preserves draft and reuses one creation key", async ({page}, testInfo) => {
  const creates: Array<{key: string | undefined; plan: Record<string, unknown>}>=[];
  page.on("request", request => { if (request.method()==="POST" && new URL(request.url()).pathname==="/api/v2/research/plans")
    creates.push({key: request.headers()["idempotency-key"],plan: request.postDataJSON()}); });
  await page.goto(`/?actor=${randomUUID()}`);
  const save=page.getByRole("button",{name: "Save plan",exact: true});
  await expect(save).toBeEnabled();
  const question=`Synthetic interrupted save ${testInfo.project.name}`;
  await page.getByLabel("Question",{exact: true}).fill(question);
  await page.getByLabel("Completion criteria").fill("Inspect source");
  await save.click();
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(page.getByLabel("Question",{exact: true})).toHaveValue(question);
  await expect(page.getByRole("status")).toHaveCount(0);
  await save.click();
  await expect(page.getByRole("status")).toHaveText("Saved draft. Execution has not started.");
  expect(creates).toHaveLength(2);
  expect(creates[0].key).toBeTruthy();
  expect(creates[0].key).toBe(creates[1].key);
  expect(creates[0].plan.plan_id).toBe(creates[1].plan.plan_id);
  await page.reload();
  await expect(page.getByRole("button",{name: `Open research plan: ${question}`,exact: true})).toHaveCount(1);
});
